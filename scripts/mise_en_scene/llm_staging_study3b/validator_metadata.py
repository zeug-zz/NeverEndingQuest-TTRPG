VALIDATOR_METADATA_OUTCOMES = MappingProxyType(
    {
        **{pair: "CONTRACT_FAILURE" for pair in _OUTPUT_CONTRACT_PAIRS},
        **{pair: "HARNESS_FAILURE" for pair in _HARNESS_FAILURE_PAIRS},
    }
)


def validator_metadata_outcome(code: object, rule_id: object) -> str | None:
    """Return the outcome for one exact frozen-validator pair, if known."""

    if type(code) is not str or type(rule_id) is not str:
        return None
    return VALIDATOR_METADATA_OUTCOMES.get((code, rule_id))


