import { readFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(await readFile(resolve(root, "package-lock.json"), "utf8"));
const packages = lock.packages;
const direct = new Set([
  ...Object.keys(packages[""]?.dependencies ?? {}),
  ...Object.keys(packages[""]?.devDependencies ?? {})
]);
const shipped = new Set([
  "react", "react-dom", "scheduler", "socket.io-client", "engine.io-client",
  "socket.io-parser", "@socket.io/component-emitter", "debug", "ms"
]);
const REVIEWED_LICENSE_ANNOTATIONS = new Map([
  ["lightningcss@1.33.0", "Overseer accepted 2026-11-06T18:55:13Z (owner may veto): MPL-2.0, dev-only Vite build tooling, not shipped in dist."],
  ["xmlhttprequest-ssl@2.1.2", "Overseer accepted 2026-11-06T18:55:13Z (owner may veto): MIT per shipped LICENSE; package-lock.json has no license field and package.json uses legacy licenses[]."],
]);
const rows = [];
const licenses = new Map();

for (const [location, entry] of Object.entries(packages)) {
  if (!location || !location.startsWith("node_modules/")) continue;
  const name = location.slice("node_modules/".length);
  let manifest = {};
  try {
    manifest = JSON.parse(await readFile(resolve(root, location, "package.json"), "utf8"));
  } catch {}
  const manifestLicense = manifest.license ?? manifest.licenses?.[0]?.type;
  const license = entry.license ?? manifestLicense ?? "UNKNOWN";
  const isDirect = direct.has(name);
  const environment = isDirect
    ? (packages[""]?.dependencies?.[name] ? "prod" : "dev")
    : (entry.dev ? "dev" : "prod");
  const optional = entry.optional ? "yes" : "no";
  const inBundle = shipped.has(name) ? "yes" : "no";
  const version = entry.version ?? manifest.version ?? "UNKNOWN";
  const displayLicense = name === "xmlhttprequest-ssl" && version === "2.1.2"
    ? `${license} (package.json fallback; lockfile field absent)`
    : license;
  rows.push({ name, version, license, displayLicense, direct: isDirect ? "direct" : "transitive", environment, optional, inBundle });
  licenses.set(license, (licenses.get(license) ?? 0) + 1);
}

rows.sort((a, b) => a.name.localeCompare(b.name));
const dependencies = Object.entries(packages[""]?.dependencies ?? {});
const devDependencies = Object.entries(packages[""]?.devDependencies ?? {});
const lines = [
  "# Frontend third-party license inventory",
  "",
  "Generated directly from `package-lock.json` and installed package manifests.",
  `Lockfile package entries: ${rows.length}.`,
  "",
  "Direct dependencies (exact approved pins):",
  ...[...dependencies, ...devDependencies].map(([name, version]) => `- ${name}@${version}`),
  "",
  "| Package | Version | License | Direct/transitive | Dev/prod | Optional | Shipped in browser bundle |",
  "| --- | --- | --- | --- | --- | --- | --- |",
  ...rows.map(({ name, version, displayLicense, direct: kind, environment, optional, inBundle }) => `| ${name} | ${version} | ${String(displayLicense).replaceAll("|", "\\|")} | ${kind} | ${environment} | ${optional} | ${inBundle} |`),
  "",
  "## Summary by license",
  "",
  "| License | Package count |",
  "| --- | ---: |",
  ...[...licenses].sort(([a], [b]) => a.localeCompare(b)).map(([license, count]) => `| ${license} | ${count} |`),
  "",
  "## License review notes",
  "",
  `- \`lightningcss\` 1.33.0 and its 11 optional platform packages: ${REVIEWED_LICENSE_ANNOTATIONS.get("lightningcss@1.33.0")} None are shipped in \`dist/\` and \`node_modules\` is not distributed.`,
  `- \`xmlhttprequest-ssl\` 2.1.2 is a production transitive of \`socket.io-client\` (Copyright (c) 2010 passive.ly LLC): ${REVIEWED_LICENSE_ANNOTATIONS.get("xmlhttprequest-ssl@2.1.2")}`,
  "- `lru-cache` 11.5.3 is BlueOak-1.0.0 (permissive), dev-only.",
  "",
  "Owner/Overseer review: ACCEPTED by Overseer 2026-11-06T18:55:13Z; owner may veto.",
  "",
  "Generated by: `node web/frontend/scripts/license-inventory.mjs`",
];
console.log(lines.join("\n"));
